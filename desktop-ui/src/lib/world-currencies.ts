export function searchWorldCurrencies(
  query: string,
  locale: AppLocale = "en",
): WorldCurrency[] {
  const q = query.trim().toLowerCase();
  if (!q) return WORLD_CURRENCIES;
  return WORLD_CURRENCIES.filter((c) =>
    currencySearchHaystack(c, locale).includes(q),
  );
}
