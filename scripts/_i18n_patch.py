def json_str(v: str) -> str:
    if "\n" in v:
        esc = v.replace("\\", "\\\\").replace("`", "\\`")
        return "`" + esc + "`"
    esc = v.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{esc}"'


def insert_keys_types(text: str, section: str, keys: list[str]) -> str:
    pattern = rf"(  {section}: \{{)(.*?)(\n  \}};)"
    m = re.search(pattern, text, re.S)
    if not m:
        raise SystemExit(f"section {section} not found in types")
    body = m.group(2)
    for k in keys:
        if re.search(rf"\n    {k}: string;", body):
            continue
        body = body.rstrip() + f"\n    {k}: string;"
    return text[: m.start()] + m.group(1) + body + m.group(3) + text[m.end() :]


def insert_keys_dict(text: str, section: str, pairs: list[tuple[str, str]]) -> str:
    pattern = rf"(  {section}: \{{)(.*?)(\n  \}},)"
    m = re.search(pattern, text, re.S)
    closing = r"\n  \},"
    if not m:
        pattern2 = rf"(  {section}: \{{)(.*?)(\n  \}}\n\}};)"
        m = re.search(pattern2, text, re.S)
        if not m:
            raise SystemExit(f"section {section} not found in dict")
        closing = "END"
    body = m.group(2)
    for k, v in pairs:
        if re.search(rf"\n    {k}:", body):
            continue
        body = body.rstrip() + f"\n    {k}: {json_str(v)},"
    if closing == "END":
        return text[: m.start()] + m.group(1) + body + m.group(3) + text[m.end() :]
    return text[: m.start()] + m.group(1) + body + m.group(3) + text[m.end() :]


def fix_values(text: str, fixes: dict[str, str]) -> str:
    """Replace leaf values for keys; skip keys that appear in NEW to avoid clobbering."""
    new_keys = {k for items in NEW.values() for k, *_ in items}
    for k, v in fixes.items():
        if k in new_keys:
            continue
        text, _ = re.subn(
            rf"(\n    {k}: )(?:\"(?:\\.|[^\"\\])*\"|`(?:\\.|[^`\\])*`)",
            rf"\1{json_str(v)}",
            text,
            count=0,
        )
    return text


